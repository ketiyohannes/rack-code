export type IconName = keyof typeof ICONS;

/** Creates a decorative icon element; pass `label` when the icon carries meaning on its own. */
export function icon(name: IconName, options: { readonly label?: string; readonly className?: string } = {}): HTMLElement {
  const element = document.createElement("span");
  element.className = options.className ? `icon ${options.className}` : "icon";
  element.innerHTML = ICONS[name];
  if (options.label === undefined) {
    element.setAttribute("aria-hidden", "true");
  } else {
    element.setAttribute("role", "img");
    element.setAttribute("aria-label", options.label);
    element.title = options.label;
  }
  return element;
}
